#!/usr/bin/env node
// Self-host the candidate fonts: copies WOFF2 files (latin, latin-ext, vietnamese
// subsets only) from the @fontsource npm packages into public/assets/fonts/,
// copies each OFL licence, and writes @font-face CSS that points at the local files.
// A tiny "IBRD Sym" subset (≈ ≥ ≤ ↩ → ← ↑ ↓ § …) is cut from IBM Plex Sans (OFL),
// because the fontsource subsets of the display/body fonts do not contain them.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const nm = path.join(root, 'node_modules');
const out = path.join(root, 'public/assets/fonts');
const SUBSETS = ['latin', 'latin-ext', 'vietnamese'];

// [package, weights, italics]
const FAMILIES = [
  ['be-vietnam-pro', [300, 400, 500, 600, 700], [400, 500]],
  ['cormorant', [300, 400, 500, 600], [300, 400, 500]],
  ['cormorant-sc', [400, 500, 600], []],
  ['playfair-display', [400, 500, 600], [400]],
  ['source-serif-4', [400, 600], [400]],
  ['newsreader', [300, 400, 500], [300, 400]],
  ['ibm-plex-sans', [400, 500, 600], [400]],
  ['ibm-plex-mono', [400, 500], []],
  ['fraunces', [300, 400], [300]],
];

fs.mkdirSync(out, { recursive: true });
const css = [];
const licences = [];
for (const [pkg, weights, italics] of FAMILIES) {
  const src = path.join(nm, '@fontsource', pkg);
  const dst = path.join(out, pkg);
  fs.mkdirSync(dst, { recursive: true });
  fs.copyFileSync(path.join(src, 'LICENSE'), path.join(dst, 'OFL.txt'));
  licences.push(pkg);
  const files = [...weights.map((w) => `${w}.css`), ...italics.map((w) => `${w}-italic.css`)];
  for (const f of files) {
    const text = fs.readFileSync(path.join(src, f), 'utf8');
    for (const block of text.split('/*').slice(1)) {
      const name = block.slice(0, block.indexOf('*/')).trim(); // e.g. be-vietnam-pro-vietnamese-400-normal
      const sub = SUBSETS.find((s) => name === `${pkg}-${s}-${name.split('-').slice(-2).join('-')}`);
      if (!sub) continue;
      const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      fs.copyFileSync(path.join(src, 'files', woff2), path.join(dst, woff2));
      const face = block.slice(block.indexOf('@font-face'))
        .replace(/src:[^;]+;/, `src: url(/assets/fonts/${pkg}/${woff2}) format('woff2');`)
        .trim();
      css.push(face);
    }
  }
}

// Symbol subset from IBM Plex Sans (complete build contains every glyph we need).
const symChars = '≈≥≤↩→←↑↓§×±·–—‘’“”…•';
const plex = path.join(nm, '@ibm/plex-sans/fonts/complete/woff2/IBMPlexSans-Regular.woff2');
const symDir = path.join(out, 'ibrd-sym');
fs.mkdirSync(symDir, { recursive: true });
fs.copyFileSync(path.join(nm, '@ibm/plex-sans/LICENSE.txt'), path.join(symDir, 'OFL.txt'));
const unicodes = [...symChars].map((c) => 'U+' + c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0'));
execFileSync('pyftsubset', [plex, `--unicodes=${unicodes.join(',')}`, '--flavor=woff2',
  `--output-file=${path.join(symDir, 'ibrd-sym.woff2')}`]);
// Only the characters the text fonts lack are routed here (dashes/quotes stay in the text fonts).
const symRange = '≈≥≤↩→←↑↓'.split('').map((c) => 'U+' + c.codePointAt(0).toString(16).toUpperCase()).join(',');
css.push(`@font-face {\n  font-family: 'IBRD Sym';\n  font-style: normal;\n  font-display: swap;\n  font-weight: 100 900;\n  src: url(/assets/fonts/ibrd-sym/ibrd-sym.woff2) format('woff2');\n  unicode-range: ${symRange};\n}`);

fs.writeFileSync(path.join(root, 'src/styles/fonts-all.css'),
  '/* Generated by scripts/copy-fonts.mjs — self-hosted OFL fonts (see public/assets/fonts/*/OFL.txt) */\n' + css.join('\n\n') + '\n');
console.log(`fonts: ${licences.length} families + IBRD Sym, ${css.length} @font-face rules`);

// Deck stylesheet: only the faces the presentation actually uses (pair C + IBM Plex Mono + IBRD Sym).
const DECK = [
  ['Cormorant', [[300, 'normal'], [400, 'normal'], [500, 'normal'], [600, 'normal'], [400, 'italic'], [500, 'italic']]],
  ['Cormorant SC', [[500, 'normal'], [600, 'normal']]],
  ['Be Vietnam Pro', [[400, 'normal'], [500, 'normal'], [600, 'normal'], [400, 'italic']]],
  ['IBM Plex Mono', [[500, 'normal']]],
];
const deckCss = css.filter((face) => {
  if (face.includes("'IBRD Sym'")) return true;
  const fam = (face.match(/font-family: '([^']+)'/) || [])[1];
  const w = Number((face.match(/font-weight: (\d+)/) || [])[1]);
  const st = (face.match(/font-style: (\w+)/) || [])[1];
  const d = DECK.find(([f]) => f === fam);
  return d && d[1].some(([dw, ds]) => dw === w && ds === st);
});
// Metric-matched fallbacks so the swap does not move text (values measured by scripts/audit-fonts.mjs).
deckCss.push(`@font-face { font-family: 'Cormorant Fallback'; src: local('Georgia'), local('Times New Roman'), local('DejaVu Serif'); size-adjust: 86%; ascent-override: 106%; descent-override: 32%; line-gap-override: 0%; }`);
deckCss.push(`@font-face { font-family: 'Be Vietnam Fallback'; src: local('Arial'), local('Helvetica'), local('Liberation Sans'), local('DejaVu Sans'); size-adjust: 106%; ascent-override: 98%; descent-override: 26%; line-gap-override: 0%; }`);
fs.writeFileSync(path.join(root, 'src/styles/fonts.css'),
  '/* Generated by scripts/copy-fonts.mjs — deck faces only (OFL, self-hosted; licences in public/assets/fonts/*/OFL.txt) */\n' + deckCss.join('\n\n') + '\n');
console.log(`deck fonts.css: ${deckCss.length} @font-face rules`);
