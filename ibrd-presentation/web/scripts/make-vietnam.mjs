#!/usr/bin/env node
// Extract a simplified Vietnam silhouette (decorative motif only) from Natural Earth 1:50m admin-0
// (public domain) via the world-atlas npm package. Writes src/art/vietnam.js: an SVG path in a
// 300×600 box and the outline points for the 3D extrusion. No borders or routes are drawn.
import fs from 'node:fs';
import path from 'node:path';
import { feature } from 'topojson-client';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const topo = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/world-atlas/countries-50m.json'), 'utf8'));
const vn = feature(topo, topo.objects.countries).features.find((f) => f.id === '704');
const polys = vn.geometry.type === 'Polygon' ? [vn.geometry.coordinates] : vn.geometry.coordinates;
// keep the mainland ring only (largest), drop islands
const rings = polys.map((p) => p[0]).sort((a, b) => b.length - a.length);
const ring = rings[0];
const lon = ring.map((p) => p[0]); const lat = ring.map((p) => p[1]);
const [x0, x1, y0, y1] = [Math.min(...lon), Math.max(...lon), Math.min(...lat), Math.max(...lat)];
const k = Math.cos(((y0 + y1) / 2) * Math.PI / 180);
const W = (x1 - x0) * k, H = y1 - y0, s = Math.min(300 / W, 600 / H);
let pts = ring.map(([a, b]) => [((a - x0) * k * s), ((y1 - b) * s)]);
// Douglas–Peucker simplification to ~1.2 px
function dp(p, eps) { if (p.length < 3) return p; let dmax = 0, idx = 0; const [ax, ay] = p[0], [bx, by] = p[p.length - 1];
  for (let i = 1; i < p.length - 1; i++) { const [x, y] = p[i]; const d = Math.abs((by - ay) * x - (bx - ax) * y + bx * ay - by * ax) / Math.hypot(by - ay, bx - ax); if (d > dmax) { dmax = d; idx = i; } }
  return dmax > eps ? [...dp(p.slice(0, idx + 1), eps).slice(0, -1), ...dp(p.slice(idx), eps)] : [p[0], p[p.length - 1]]; }
// closed ring: split at the point farthest from the start, simplify both halves
{ const far = pts.reduce((bi, q, i) => (Math.hypot(q[0] - pts[0][0], q[1] - pts[0][1]) > Math.hypot(pts[bi][0] - pts[0][0], pts[bi][1] - pts[0][1]) ? i : bi), 0);
  pts = [...dp(pts.slice(0, far + 1), 1.2).slice(0, -1), ...dp(pts.slice(far), 1.2).slice(0, -1)]; }
const d = 'M' + pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L') + 'Z';
fs.writeFileSync(path.join(root, 'src/art/vietnam.js'), `// Generated by scripts/make-vietnam.mjs from Natural Earth 1:50m (public domain) via world-atlas. Decorative silhouette only.\nexport const VN_W = ${(W * s).toFixed(1)};\nexport const VN_H = ${(H * s).toFixed(1)};\nexport const VN_PATH = '${d}';\nexport const VN_POINTS = ${JSON.stringify(pts.map(([x, y]) => [+x.toFixed(1), +y.toFixed(1)]))};\n`);
console.log('vietnam silhouette:', pts.length, 'points', (W * s).toFixed(0) + '×' + (H * s).toFixed(0));
