#!/usr/bin/env node
// Generate SLIDES.md (the section plan) and CITATIONS.md (citation map) from src/data/deck.json,
// so the documents can never drift from what the deck shows.
import fs from 'node:fs';
import path from 'node:path';
import { plain } from '../src/lib/markup.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const d = JSON.parse(fs.readFileSync(path.join(root, 'src/data/deck.json'), 'utf8'));
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

const TPL = {
  cover: 'Cover', agenda: 'Contents (cards)', chapter: 'Chapter opener (night gallery)', hero: 'Title + bullets + hero engraving',
  cards: 'Certificate cards', compare: 'Two-column comparison', table: 'Table in certificate frame', timeline: 'Timeline',
  stats: 'Big numbers in stamps + bullets', process: 'Process ("railway line")', chart: 'Engraved chart + bullets',
  gallery: 'Night gallery: 3D hero + giant word + bullets', cycle: 'Night gallery: project-cycle ring', quote: 'Big quote',
  grid: 'Certificate grid (10 standards)', refs: 'References list', index: 'Index of sources', credits: 'Credits', thanks: 'Thank you',
};
const OBJ = { center: 'centre, full size', left: 'left of centre, full size', carousel: 'arc carousel', ring: 'ring of six pedestals' };

const lines = ['# SLIDES.md — section plan', '',
  'Generated by `scripts/make-docs.mjs` from `content/deck.yaml` (the single content source). Section numbers are',
  'the counter shown on stage (`n / N`). "2D" = hero engraving (`src/art/`), "3D" = the part\'s hero object and its slot',
  '(`src/three/`). "Notes" = verbatim paper text shown in the presenter panel (N) and in reading mode.', '',
  `Total: **${d.slides.length} sections**.`, '', '## Parts and hero objects', '',
  '| Part | Label | Giant word | 3D hero object | 2D hero set | First section |', '|---|---|---|---|---|---|'];
for (const [k, p] of Object.entries(d.parts)) lines.push(`| ${k} | ${cell(p.label)} | ${p.giant} | ${p.hero3d} | ${p.art} | ${d.partStart[k] ?? '—'} |`);
lines.push('', '## Sections', '');
let curPart = null;
for (const s of d.slides) {
  if (s.part !== curPart) { curPart = s.part; lines.push(`### ${d.parts[s.part].label}`, ''); }
  const title = s.title || (s.tpl === 'cover' ? d.meta.title : s.tpl === 'thanks' ? 'Thank you' : s.quote ? '“' + plain(s.quote).slice(0, 70) + '…”' : '');
  lines.push(`**${s.n}. ${cell(title)}** — ${TPL[s.tpl] || s.tpl} · ground: ${s.ground} · ref: ${s.ref || '—'}`);
  const bits = [];
  if (s.art) bits.push(`2D: ${s.art}`);
  if (s.obj) bits.push(`3D: ${s.hero3d} (${OBJ[s.obj] || s.obj})`); else bits.push(`3D: — (2D only)`);
  if (s.table) bits.push(`table: ${s.table}${s.highlight ? ' (row-by-row highlight)' : ''}`);
  if (s.charts) bits.push(`charts: ${s.charts.join(', ')}`);
  lines.push(`<br>${bits.join(' · ')}`, '');
  const bl = [];
  if (s.lead) bl.push(`- _Lead:_ ${plain(s.lead)}`);
  for (const b of s.bullets || []) bl.push(`- ${plain(typeof b === 'string' ? b : b.t)}`);
  for (const it of s.items || []) bl.push(typeof it === 'string' ? `- ${plain(it)}` : `- ${it.d ? it.d + ' — ' : ''}${plain(it.t || '')}${it.h ? it.h + ': ' + plain(it.b) : ''}`);
  for (const c of s.cards || []) bl.push(`- [card] ${plain(c.h)}: ${plain(c.b)}`);
  for (const c of s.steps || []) bl.push(`- [step] ${plain(c.h)}: ${plain(c.b)}`);
  for (const c of s.nums || []) bl.push(`- [number] ${c.v} — ${plain(c.l)}`);
  for (const side of ['left', 'right']) if (s[side]) { bl.push(`- [${side}] ${plain(s[side].h)}`); for (const it of s[side].items) bl.push(`  - ${plain(it)}`); }
  if (s.quote) bl.push(`- [quote] “${plain(s.quote)}” — ${s.by}`);
  if (s.foot) bl.push(`- _Foot:_ ${plain(s.foot)}`);
  if (s.refRange) bl.push(`- references [${s.refRange[0]}]–[${s.refRange[1]}]`);
  lines.push(...bl);
  if (s.notes.length) lines.push(`- _Notes (verbatim):_ ${s.notes.map((n) => n.ref).join(', ')}`);
  lines.push('');
}
fs.writeFileSync(path.join(root, 'SLIDES.md'), lines.join('\n'));

// ---------------------------------------------------------------- CITATIONS.md
const AY = [
  ['Wes (2023)', 14, 'certain', 'only Wes entry'], ['Gelb et al. (2016)', 15, 'certain', 'only Gelb entry'],
  ['World Bank Treasury (2020)', 17, 'certain', 'only Treasury 2020 entry'], ['IBRD (2025)', 19, 'certain', 'only IBRD 2025 entry'],
  ['Government of Viet Nam (2013, 2016, 2020, 2021, 2023, 2025, 2026)', '48–54', 'certain', 'one decree per year'],
  ['World Bank Treasury (n.d.-a) — fees', 16, 'inferred', 'suffix -a undefined; 1.4.2 cites [16] for the fees'],
  ['World Bank Treasury (n.d.-b) — Short Maturity Loan', 20, 'inferred', 'suffix -b undefined; 1.4.2 cites [20] for this loan'],
  ['World Bank (2014b) — maturity extension', 18, 'inferred', 'no "2014a" exists; 1.4.2 cites [18]'],
  ['World Bank (2014) / (2014, Project Data Sheet)', 44, 'inferred', '[18], [21] are also World Bank 2014'],
  ['World Bank (2017) — Table 8', 47, 'inferred', '[27], [33] are also World Bank 2017'],
  ['World Bank (2017, Annex 2, Table 2.1) — Table 18 note', 33, 'inferred', 'the same locator is cited as [33] in 3.3.2'],
  ['World Bank (2022a, …)', 41, 'inferred', 'TEP ICR; matches "Annex 3" locators cited as [41]'],
  ['World Bank (2022b, pp. 2-3)', 42, 'inferred', '[42] is authored by IEG, not World Bank'],
  ['World Bank (2022c) — Table 6', 43, 'inferred', 'by elimination: the 2022 CCSEP restructuring paper'],
  ['World Bank (2023, …)', 37, 'inferred', '[37] is authored by IEG (2023)'],
  ['World Bank, n.d.-c — ISRs (2.2.3)', 25, 'inferred', 'weakest: no n.d.-a/-b World Bank entries are identified'],
  ['"Source: projects.worldbank.org" (Tables 17–21, Figures 5–8)', '—', 'not linked', 'not a numbered reference'],
];
const C = ['# CITATIONS.md — citation map', '',
  'Generated by `scripts/make-docs.mjs`. Every number is its own link on the stage; it opens the source drawer without',
  'leaving the section (Esc, "↩ Back" or the browser Back button closes it). Locators are copied only from the paper.', '',
  '**Excerpt status.** No source could be opened from the build environment: `curl` through the proxy was refused',
  '(CONNECT 403) for every source host, and WebFetch failed with `getaddrinfo ENOTFOUND` (tested on worldbank.org and',
  'cgdev.org on 2026-10-27). Therefore **no verified excerpt exists**; every drawer says',
  '*"Source text not retrieved – shown: citation details from the paper only"*. Nothing is quoted from memory.', '',
  '| [n] | Reference (as in the paper, drafting marks removed) | Shown on sections | Locators given in the paper | Status |',
  '|---|---|---|---|---|'];
for (let n = 1; n <= 58; n++) {
  const r = d.references[n]; const c = d.cites[n];
  const status = !c.citedFor.length ? 'Not cited in the body text' :
    (c.locators.length ? 'locator only' : 'citation only (no locator in paper)') + (c.inferred.length ? ` · **mapping inferred – to be confirmed** (${c.inferred.join('; ')})` : '') + ' · excerpt not retrieved';
  C.push(`| [${n}] | ${cell(r.text)} ${r.url} | ${c.slides.join(', ') || '—'} | ${cell(c.locators.join('; ')) || 'Locator not given in the paper'} | ${status} |`);
}
C.push('', '## Author–year citations and their mapping', '',
  'The paper mixes numbered citations with author–year forms that do not exist in its numbered list. A link is',
  'treated as certain only when the mapping is unique; otherwise the drawer shows **"Mapping inferred – to be',
  'confirmed"** and the case is listed in ISSUES.md §6.', '', '| Text in the paper | Linked to | Confidence | Why |', '|---|---|---|---|');
for (const [t, n, conf, why] of AY) C.push(`| ${cell(t)} | ${typeof n === 'number' ? `[${n}]` : n} | ${conf} | ${why} |`);
fs.writeFileSync(path.join(root, 'CITATIONS.md'), C.join('\n') + '\n');
console.log(`make-docs: SLIDES.md (${d.slides.length} sections), CITATIONS.md (58 sources)`);
