#!/usr/bin/env python3
"""Generate SLIDES.md and CITATIONS.md from content/deck.yaml + build/build-info.json + the built pptx,
so the documentation always matches the deck."""
import json, re, sys, pathlib, collections
from pptx import Presentation

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import deckkit as K

ROOT = K.ROOT
info = json.loads((ROOT / "build/build-info.json").read_text(encoding="utf-8"))
prs = Presentation(ROOT / "IBRD-Presentation.pptx")
slides = list(prs.slides)
D = K.load_deck()
specs = [s for s in D["slides"] if s["kind"] not in ("references", "index", "credits", "thanks")]


def morph_names(sl):
    return [sh.name for sh in sl.shapes if sh.name.startswith("!!")]


def dur(sl):
    x = sl._element
    m = re.search(rb'p14:dur="(\d+)"', __import__("lxml.etree", fromlist=["tostring"]).tostring(x))
    return m.group(1).decode() if m else "—"


# ------------------------------------------------------------------ SLIDES.md
L = ["# SLIDES.md — slide list", "",
     "Generated by `scripts/make_docs.py` from the slide plan `content/deck.yaml` (written before the deck was built)",
     "and the built `IBRD-Presentation.pptx`. Morph objects are the shapes named `!!…`; a shape with the same name on",
     "two adjacent slides is morphed by PowerPoint, anything else fades.", "",
     f"Visible slides: **{info['visible_slides']}** · hidden source-card pages: **{info['card_slides']}** "
     f"(one or more per reference [1]–[58]).", "",
     "| # | Kind | Section | Title | Paper § / pages | On-slide content | Morph objects (besides !!bg, !!compass, !!dot1-3) | Morph ms |",
     "|---|---|---|---|---|---|---|---|"]
for rec in info["slides"]:
    sl = slides[rec["no"] - 1]
    spec = next((s for s in specs if s.get("title", s["kind"]) == rec["title"] and s["section"] == rec["section"]), {})
    k = rec["kind"]
    content = {
        "bullets": lambda s: f"{len(s['bullets'])} bullets + art ({s.get('art')})",
        "cards": lambda s: f"{len(s['cards'])} cards" + (" + lead line" if s.get("lead") else ""),
        "bignums": lambda s: f"{len(s['nums'])} key numbers + {len(s['bullets'])} bullets",
        "timeline": lambda s: f"timeline, {len(s['items'])} events",
        "table": lambda s: f"{s['table']} (native table)" + (f" rows {s['rows']}" if s.get("rows") else "") + (f" cols {s['cols']}" if s.get("cols") else ""),
        "table_chart": lambda s: f"{s['table']} + native chart {s['chart']}",
        "table_nums": lambda s: f"{s['table']} + key numbers",
        "chart": lambda s: f"native chart {s['chart']} + {len(s['bullets'])} bullets",
        "chart_image": lambda s: f"native chart {s['chart']} + original Figure 8 images + bullets",
        "flow": lambda s: f"funding flow diagram ({len(s['steps'])} boxes) + bullets",
        "cycle": lambda s: "six-stage cycle diagram",
        "grid": lambda s: "ESS1–ESS10 grid",
        "divider": lambda s: f"giant word + chapter title + art ({s.get('art')})",
        "cover": lambda s: "title, group, members, class, lecturer placeholder",
        "agenda": lambda s: "5 linked agenda cards",
    }.get(k, lambda s: k)(spec) if spec else k
    names = [n for n in morph_names(sl) if n not in ("!!bg", "!!compass", "!!dot1", "!!dot2", "!!dot3")]
    pages = ""
    if spec:
        from build_deck import notes_for, pages_str  # noqa
        pages = pages_str(notes_for(spec)[1])
    L.append(f"| {rec['no']} | {k} | {rec['section']} | {rec['title']} | {rec['ref'] if rec['ref'] != k else ''}"
             f"{(' · p. ' + pages) if pages else ''} | {content} | {', '.join('`'+n+'`' for n in names)} | {dur(sl)} |")
L += ["", "## Source-card pages (hidden, `show=\"0\"`, no transition)", "",
      "| Source | Card pages |", "|---|---|"]
for n, c in sorted(info["card_pages"].items(), key=lambda x: int(x[0])):
    L.append(f"| [{n}] | {c} |")
(ROOT / "SLIDES.md").write_text("\n".join(L) + "\n", encoding="utf-8")

# ------------------------------------------------------------------ CITATIONS.md
ay = []
blob = json.dumps(D, ensure_ascii=False)
for m in K.AY.finditer(blob):
    ay.append((m.group(1), int(m.group(2)), m.group(3)))
ay = sorted(set(ay), key=lambda x: (x[1], x[0]))
C = ["# CITATIONS.md — citation map", "",
     "Generated by `scripts/make_docs.py`. Every number below is a separate hyperlink on the slides that opens the",
     "source card; the card's **Back** button returns to the slide last viewed. Locators are copied only from the paper.", "",
     "**Excerpt status.** The build environment could not reach any source website (both `curl` and WebFetch were",
     "refused by the network proxy), so **no source text was retrieved and no excerpt is quoted**. Every card is labelled",
     "*“Source text not retrieved – shown: citation details from the paper only”*.", "",
     "| [n] | Reference (paper, drafting marks removed) | Cited on slides | Locators given in the paper | Status |",
     "|---|---|---|---|---|"]
uses = info["usages"]
for n in sorted(K.load_paper()["refs"]):
    text, url = K.ref_parts(n)
    u = uses.get(str(n), [])
    sl = sorted({e["slide_no"] for e in u})
    locs = sorted({e["locator"] for e in u if e["locator"] and not e.get("ay")})
    infer = sorted({e["ay_text"] for e in u if e.get("ay") == "inferred"})
    status = "not cited in the body text" if not u else ("locator only" if locs else "citation only (no locator in paper)")
    if infer:
        status += "; **mapping inferred – to be confirmed** (" + "; ".join(infer) + ")"
    status += "; excerpt not retrieved"
    C.append(f"| [{n}] | {text}{(' ' + url) if url else ''} | {', '.join(map(str, sl)) or '—'} | "
             f"{'; '.join(locs) or 'Locator not given in the paper'} | {status} |")
C += ["", "## Author–year citations in tables, figure sources and text", "",
      "The paper mixes numbered citations with author–year citations (e.g. *World Bank (2022a, Annex 3, Table 3.2, p. 49)*)",
      "that do not appear in its numbered reference list. They are linked as follows; **inferred** ones are flagged on the",
      "card and listed in ISSUES.md for confirmation.", "",
      "| Author–year text on slide | → [n] | Confidence | Reasoning |", "|---|---|---|---|"]
why = {
    14: "only reference by Wes (2023)", 15: "only reference by Gelb et al. (2016)", 17: "only World Bank Treasury (2020) entry",
    19: "only IBRD (2025) entry", 48: "only Government of Vietnam 2013 entry", 49: "only 2016 decree", 50: "only 2020 decree",
    51: "only 2021 decree", 52: "only 2023 decree", 53: "only 2025 decree", 54: "only 2026 decree",
}
for txt, n, conf in ay:
    r = why.get(n, "")
    if not r:
        r = {41: "World Bank 2022 ICR for TEP; the body text cites [41, Annex 3] for the same Annex 3 tables",
             42: "body text cites [42, pp. 2–3] for the same content; but [42] is authored by IEG, not World Bank",
             43: "by elimination: the other World Bank 2022 document (CCSEP Restructuring Paper)",
             37: "body text cites [37] (IEG 2023 PPAR) for the same pages/figures; authored by IEG, not World Bank",
             44: "TEP PAD (2014); [18] and [21] are also World Bank 2014 entries",
             47: "SAHEP PAD (2017); [27] and [33] are also World Bank 2017 entries",
             33: "CCSEP PAD (2017); body text cites [33, Annex 2, Table 2.1]",
             18: "February 2014 loan-terms press release; body text cites [18] for the same maturity change; '2014b' suffix undefined",
             20: "body text cites [20] for the Short Maturity Loan; suffix '-b' undefined",
             16: "body text cites [16] for the fees; suffix '-a' undefined",
             25: "suffix '-c' undefined; [25] (project cycle) is the closest World Bank n.d. source for ISRs"}.get(n, "")
    C.append(f"| {txt} | [{n}] | {conf} | {r} |")
C += ["", "## Source lines not linked", "",
      "`Source: projects.worldbank.org` (Tables 17–21, Figures 5–8) is not a numbered reference; it is shown verbatim and",
      "not linked (see ISSUES.md)."]
(ROOT / "CITATIONS.md").write_text("\n".join(C) + "\n", encoding="utf-8")
print("wrote SLIDES.md, CITATIONS.md")
